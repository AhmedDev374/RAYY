def hours_to_lux(hours: float) -> float:
    """Kept identical to the original conversion so existing ideal-conditions
    gauges (which expect lux) keep rendering correctly."""
    return hours * 150.0


def _t(soil, temp, hum, sun_hours):
    return {
        "soil_moisture": {"min": soil[0], "max": soil[1], "ideal": soil[2]},
        "temperature": {"min": temp[0], "max": temp[1], "ideal": temp[2]},
        "humidity": {"min": hum[0], "max": hum[1], "ideal": hum[2]},
        "light": {
            "min": hours_to_lux(sun_hours[0]),
            "max": hours_to_lux(sun_hours[1]),
            "ideal": hours_to_lux(sun_hours[2]),
        },
    }


