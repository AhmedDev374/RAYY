"""
Structured, Arabic-first data for the Plant Encyclopedia (موسوعة رَيّ).

This module is the single source of truth for encyclopedia content. It is
consumed by `app.seed` (to populate `species_profiles` on first boot) and can
be imported anywhere else the raw category metadata is needed (e.g. to build
an `/encyclopedia/categories` endpoint).

Design notes
------------
- `species` is the stable English key used everywhere else in the codebase
  (routes, the AI model, disease reports, etc.) — e.g. "Tomato". It is NOT
  translated, so existing integrations (diagnosis, chat, disease-map) keep
  working unchanged.
- All *_ar fields are professional Modern Standard Arabic and are the only
  copy shown in the UI.
- `thresholds` reuses the original architecture: soil_moisture / temperature
  / humidity are percentages / °C, and `light` is stored in lux (converted
  from a reference daily sun-hours figure, exactly like the original
  `hours_to_lux` helper), so `SpeciesProfileOut.thresholds` stays
  drop-in compatible with the existing frontend gauge component.
- `ai_support` is intentionally always `{"supported": False, "model": None}`
  here. This project has no knowledge of the user's locally modified
  AgroScan model or its `labels.json`, so real compatibility values must be
  supplied later from that project — never guessed or hard-coded.
"""

